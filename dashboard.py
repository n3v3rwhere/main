import os
from decimal import Decimal, InvalidOperation  # Import Decimal to handle monetary values accurately
from dotenv import load_dotenv
from sqlalchemy import create_engine, text
from sqlalchemy.exc import SQLAlchemyError

load_dotenv()

def get_engine():                                  # Define a function to create and return a SQLAlchemy engine
    """Create and return a SQLAlchemy engine from DATABASE_URL."""
    url = os.getenv("DATABASE_URL")                # Read the DATABASE_URL from the environment 

    if not url:                                    # Raise an error if DATABASE_URL is not configured
        raise ValueError(
            "DATABASE_URL is missing. Check your .env file."
        )

    return create_engine(url, pool_pre_ping=True)  # Create and return a SQLAlchemy engine with connection pooling enabled



def store_report(engine):                          # Define a function that displays store statistics and reports
    with engine.connect() as conn:                 # Establish a connection to the database; Close it automatically afterwards
        users = conn.execute(
            text("SELECT COUNT(*) FROM users")     # Execute a SQL query to count the number of users
        ).scalar_one()                             # Retrieve the result as a single scalar value


        products = conn.execute(
            text("SELECT COUNT(*) FROM products")  # Execute a SQL query to count the number of products
        ).scalar_one()                             # Retrieve the result as a single scalar value


        orders = conn.execute(
            text("SELECT COUNT(*) FROM orders")    # Execute a SQL query to count the number of orders
        ).scalar_one()                             # Retrieve the result as a single scalar value

        print("\n=== Store Dashboard ===")          # Print the store dashboard header
        print(
            f"Users: {users} | "                    # Print the counts of users, products, and orders
            f"Products: {products} | "
            f"Orders: {orders}"
        )


        catalog = conn.execute(                     # Retrieve all products, sorted automatically by name
            text("""                                
                SELECT name, price, stock
                FROM products
                ORDER BY name
            """)                                    # Select the name, price, and available stock of each product
        ).fetchall()                                # Fetch all results 


        print("\nCatalog:")                         # Print the catalog header
       
       
       
        for product in catalog:                     # Loop through each product in the catalog and print its details
            print(
                f"{product.name:<12}"
                f"${product.price:>7.2f}"
                f"(stock{product.stock})"
            )
        top_customers = conn.execute(               # Retrieve the top 3 customers based on total spending
            text("""                                      
                SELECT 
                    u.email,
                    SUM(o.quantity) as total_items
                FROM users AS u
                JOIN orders AS o
                    ON u.id = o.user_id
                GROUP BY u.id, u.email
                ORDER BY total_items DESC, u.email ASC
                LIMIT 3
            """)                                     # Join users and orders and calculate purchased quantities
        ).fetchall()                                 # Fetch all results

        print("\nTop Customers:")                        

        for customer in top_customers:               # Loop through each top customer and print their details
            print(
                f"{customer.email:<25}"
                f"- {customer.total_items} items"       
            )



def store_extra_reports(engine):                            # Define a function that displays additional store reports

    with engine.connect() as conn:
        # LOW STOCK ALERT
        low_stock = conn.execute(
            text("""
                SELECT name, stock
                FROM products
                WHERE stock < 10
                ORDER BY stock ASC, name ASC
            """)
        ).fetchall()

        print("\n===Low Stock Alert===")
        if low_stock:
            for product in low_stock:
                print(
                    f"{product.name:<15}"
                    f"- only {product.stock} left"
                )
        else:                                               # Situation when all products are sufficiently stocked
            print("All products are sufficiently stocked.")


        # REVENUE PER PRODUCT (Calculate the total revenue generated by each product)
        revenue = conn.execute(
            text("""
                SELECT
                    p.name,
                    COALESCE(SUM(o.quantity * p.price), 0) AS total_revenue
                FROM products AS p
                LEFT JOIN orders AS o
                    ON p.id = o.product_id
                GROUP BY p.id, p.name
                ORDER BY total_revenue DESC, p.name ASC
            """)                                            # Join products with orders and calculate total revenue
        ).fetchall()

        print("\n===Revenue per Product===")
        for product in revenue:                             # Loop through each product and print its name and total revenue
            print(
                f"{product.name:<15}"
                f"$ {product.total_revenue:,.2f}"
            )

        # USERS WITHOUT ORDERS
        inactive_users = conn.execute(
            text("""
                SELECT
                    u.id,
                    u.email
                FROM users AS u
                LEFT JOIN orders AS o
                    ON u.id = o.user_id
                WHERE o.id IS NULL
                ORDER BY u.email 
                """)                                        # Identify users who have never placed an order
        ).fetchall()


        print("\n=== Users Without Orders ===")

        if inactive_users:                          
            for user in inactive_users:    
                print(
                    f"ID:{user.id:<5}"
                    f"Email: {user.email}"
                )
        else:                                               # Situation when all users have placed orders
            print("All users have placed orders.")



def add_product(engine, name, category, price, stock):      # Define a function to add a new product to the database
   
   
    with engine.connect() as conn:                          
        result = conn.execute(                              # Execute an SQL query to insert a new product into the products table
            text("""
                INSERT INTO products 
                      (name, category, price, stock)
                VALUES 
                      (:name, :category, :price, :stock)
                RETURNING id
            """),
            
            # Bind parameters to prevent SQL injection and ensure proper data handling
            {
            "name": name,
            "category": category,
            "price": price,
            "stock": stock  
            }
        )
        product_id = result.scalar_one()                      # Retrieve the ID of the newly inserted product
    return product_id                                        



def place_order(engine, email, product_name, quantity):       # Define a function that creates an order and decreases product stock

    if quantity <= 0:                                         # Validate that the quantity is a positive integer
        raise ValueError("Quantity must be greater than zero.")

    with engine.connect() as conn:                             
        user = conn.execute(                                  # Execute an SQL query to find the user by email
            text("""
                SELECT id
                FROM users
                WHERE email = :email
            """),                                             # Pass the email as a named SQL parameter to prevent SQL injection

            {"email": email}                                        
        ).fetchone()

    if user is None:                                          # Raise an error if the user does not exist
        raise ValueError(f"User not found: {email}")

    product = conn.execute(                                   # Execute an SQL query to find the product by name
        text("""
            SELECT id, stock
            FROM products
            WHERE name = :product_name
            FOR UPDATE
        """),                                                 # Pass the product name as a named SQL parameter to prevent SQL injection
            
        {"product_name": product_name}
    ).fetchone()

    if product is None:                                       # Raise an error if the product does not exist
        raise ValueError(f"Product not found: {product_name}")

    if product.stock < quantity:                              # Raise an error if there is insufficient stock for the order
        raise ValueError(
            f"Insufficient stock. Available: {product.stock}" 
            f"requested: {quantity}"
        )

    result = conn.execute(                                    # Execute an SQL query to insert a new order into the orders table
        text("""
            INSERT INTO orders (user_id, product_id, quantity)
            VALUES (:user_id, :product_id, :quantity)
            RETURNING id
        """),
        {
            "user_id": user.id,
            "product_id": product.id,
            "quantity": quantity
        }
    )                                                         # Pass the user ID, product ID, and quantity as named SQL parameters to prevent SQL injection

    order_id = result.scalar_one()                            # Retrieve the ID of the newly inserted order

    conn.execute(                                             # Execute an SQL query to update the product stock after placing the order
        text("""
            UPDATE products
            SET stock = stock - :quantity
            WHERE id = :product_id
        """),
        {
            "quantity": quantity,
            "product_id": product.id
        }
    )                                                         # Pass the quantity and product ID as named SQL parameters to prevent SQL injection    
    return order_id   



def main():
    
    try:
        engine = get_engine()                                 # Create a SQLAlchemy engine using the get_engine function
        store_report(engine)                                  # Call the store_report function to display store statistics and reports
        store_extra_reports(engine)                           # Call the store_extra_reports function to display additional store reports

        while True:                                              # Start an infinite loop to continuously prompt the user for actions
            print("\n=== Store Management ===")                  
            print("1. Add Product")                              # Display options for the user to choose from
            print("2. Place Order")
            print("3. Refresh Dashboard")
            print("0. Exit")

            choice = input("\nChoose an option: ").strip()                                    # Prompt the user to choose an option

            if choice == "1":                                                                 # If the user chooses to add a product
                try:
                    name = input("Product Name: ").strip()                                    # Prompt the user for product details
                    category = input("Category: ").strip()
                    price = input("Price: ").strip()
                    stock = input("Stock: ").strip()

                    if not name or not category:
                        raise ValueError("Product name and category cannot be empty.")        # Validate that product name and category are not empty

                    if not  price.is_finite() or price < 0:
                        raise ValueError("Price must be a non-negative number.")              # Validate that price is a non-negative number

                    if stock < 0:
                        raise ValueError("Stock cannot be negative.")                         # Validate that stock is a non-negative number


                    product_id = add_product(engine, name, category, price, stock)            # Call the add_product function to add the new product to the database
                    print(f"Product added successfully. ID: {product_id}")  

                except (ValueError, InvalidOperation) as e:                                   # Handle any validation errors that occur during product addition
                    print(f"Input Error: {e}")

                except SQLAlchemyError as e:                                                  # Catch database errors during product insertion.
                    print(f"Database Error: {e}")
            

            elif choice == "2":                                                               # If the user chooses to place an order
            
                try:
                    email = input("Customer email: ").strip()                                 # Prompt the user for order details
                    product_name = input("Product name: ").strip()
                    quantity = int(input("Quantity: ").strip())
                    order_id = place_order(engine, email, product_name, quantity)             # Call the place_order function to create a new order and decrease product stock

                    print(f"Order placed successfully. ID: {order_id}")

                except ValueError as e:                                                       # Handle any validation errors that occur during order placement
                    print(f"Order Error: {e}")   
                except SQLAlchemyError as e:                                                  # Handle any database errors that occur during order placement
                    print(f"Database Error: {e}")

            elif choice == "3":                                                               # If the user chooses to refresh the dashboard 
                store_report(engine)                                                          # Call the store_report function to display updated store statistics and reports
                store_extra_reports(engine)                                                   # Call the store_extra_reports function to display updated additional store reports

            elif choice == "0":                                                               # If the user chooses to exit the program    
                    print("Goodbye!")
           
                    break

            else:
                    print("Invalid option. Please try again.")                                 # Handle invalid menu options

        engine.dispose()                                                                       # Dispose of the SQLAlchemy engine to close all connections
    
    except (ValueError, SQLAlchemyError) as e:                                                 # Handle any errors that occur during the main execution
        print(f"Application Error: {e}")


if __name__ == "__main__":                                                                      # Check if the script is being run directly (not imported as a module)
    main()                                                                                      # Start the main function to run the store management application